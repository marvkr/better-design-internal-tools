import * as React from "react";

import { cn } from "@/lib/utils";

/*
 * Ops Sharp Card — a crisp white ops panel.
 *
 * Pure white surface, a hairline border, and a tight low-spread shadow so the
 * panel sits a hair above the grey canvas without floating. Sharp 8px corner.
 */

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-lg border border-border bg-card text-card-foreground",
      "[box-shadow:var(--shadow-s)]",
      className
    )}
    {...props}
  />
));
Card.displayName = "Card";

